"""sqlite-query: the net revenue of one month's orders by customers of one region, from a
SQLite database (Python's sqlite3 module; the image has no sqlite3 CLI).

Construction: `/app/data/shop.db` holds `customers` and `orders` (hard adds `addresses`).
The answer is SUM(amount_cents - COALESCE(refunded_cents, 0)) over the qualifying orders, in
dollars. Traps, planted in every instance:

- `refunded_cents` is NULL for most orders, so `amount_cents - refunded_cents` silently
  drops them from the SUM (`null-drop`); some qualifying orders have refunds (`gross`).
- soft-deleted orders (`deleted_at` set) qualify otherwise (`deleted-orders`); medium/hard
  also soft-delete a customer of the region who has qualifying orders (`deleted-customers`).
- medium/hard: `created_at` (cart opened) is a misleading date column: orders placed on the
  first day of the month were opened the month before, and never-placed carts were opened
  in the month (`created-at`).
- hard: the region is the customer's *primary* address; customers have several addresses,
  so joining all addresses double-counts (`address-join`) or admits customers whose only
  address in the region is secondary (`any-address`), and `orders.region` (the shipping
  warehouse) is another misleading column (`order-region`).

Every solution is one Python source (`SOLVER`) run with a mode, as in csv_revenue: the shell
form queries /app/data/shop.db, the model runs the same queries on the generated bytes.

The database is built in a temporary directory with sqlite3 and read back. Two things would
otherwise make the bytes depend on the host's SQLite version: the header field holding the
writing library's version number (offset 96), which is set to a constant, and stale bytes in
the unused space of b-tree pages after a page split, which SQLite 3.46 zeroes and 3.50 does
not; `PRAGMA secure_delete` makes every version zero them. With both, the file is identical
under SQLite 3.46 (the task image) and 3.50.
"""

import os
import sqlite3
import struct
import tempfile
from datetime import datetime, timedelta

from learning_loop.tasks.spec import Family, NumericAnswer, Reject, Solution, TaskSpec

REGIONS = ["north", "south", "east", "west", "central"]
MONTHS = ["March", "April", "May", "June", "July", "August", "September", "October"]  # month numbers 3..10
FIRST_NAMES = ["Ada", "Bruno", "Chen", "Dara", "Elif", "Femi", "Gita", "Hugo", "Ines", "Jonas", "Kofi", "Lena", "Mei", "Nils", "Omar", "Pia"]
LAST_NAMES = ["Novak", "Okafor", "Silva", "Berg", "Kaya", "Moreau", "Tanaka", "Haddad", "Lund", "Rossi"]
SQLITE_VERSION_FIELD = 3046001  # written at header offset 96 instead of the host library's version

INSTRUCTION = """The shop's database is the SQLite file `/app/data/shop.db`. The `sqlite3` command-line tool is not installed, but Python's `sqlite3` module is.

What was the total **net revenue**, in dollars, of the orders placed in {month} 2026 by customers in the `{region}` region?

{rules}

Write the amount in dollars with two decimals (for example `1234.50`), and nothing else, to `/app/answer.txt`.
"""

RULES = {
    1: [
        "An order's net revenue is `amount_cents` minus `refunded_cents`. `refunded_cents` is NULL when nothing was refunded.",
        "The month of an order is the month of its `placed_at`.",
        "Orders whose `deleted_at` is set were deleted; leave them out.",
        "A customer's region is `customers.region`.",
    ],
    2: [
        "An order's net revenue is `amount_cents` minus `refunded_cents`. `refunded_cents` is NULL when nothing was refunded.",
        "The month of an order is the month of its `placed_at` (`created_at` is when the shopping cart was opened; carts that were never checked out have no `placed_at`).",
        "Rows whose `deleted_at` is set were deleted: leave out deleted orders and every order of a deleted customer.",
        "A customer's region is `customers.region`.",
    ],
    3: [
        "An order's net revenue is `amount_cents` minus `refunded_cents`. `refunded_cents` is NULL when nothing was refunded.",
        "The month of an order is the month of its `placed_at`.",
        "Rows whose `deleted_at` is set were deleted: leave out deleted orders and every order of a deleted customer.",
        "A customer's region is the region of their primary address (`addresses.is_primary = 1`).",
    ],
}

SOLVER = '''
def answer(con, level, region, start, end, mode):
    """Net revenue in cents of the orders the mode's query selects."""
    if mode == "gross":
        net = "o.amount_cents"
    elif mode == "null-drop":
        net = "o.amount_cents - o.refunded_cents"
    else:
        net = "o.amount_cents - COALESCE(o.refunded_cents, 0)"
    date = "o.created_at" if mode == "created-at" else "o.placed_at"
    joins = "JOIN customers c ON c.id = o.customer_id"
    where = [date + " >= ?", date + " < ?"]
    args = [start, end]
    if mode != "deleted-orders":
        where.append("o.deleted_at IS NULL")
    if level >= 2 and mode != "deleted-customers":
        where.append("c.deleted_at IS NULL")
    if level == 1 or level == 2:
        where.append("c.region = ?")
    elif mode == "order-region":
        where.append("o.region = ?")
    elif mode == "address-join":
        joins += " JOIN addresses a ON a.customer_id = c.id"
        where.append("a.region = ?")
    elif mode == "any-address":
        where.append("c.id IN (SELECT customer_id FROM addresses WHERE region = ?)")
    else:
        joins += " JOIN addresses a ON a.customer_id = c.id AND a.is_primary = 1"
        where.append("a.region = ?")
    args.append(region)
    sql = "SELECT COALESCE(SUM(" + net + "), 0) FROM orders o " + joins + " WHERE " + " AND ".join(where)
    return con.execute(sql, args).fetchone()[0]
'''

_SHELL = """python3 - <<'PY'
{solver}
import sqlite3

con = sqlite3.connect("file:/app/data/shop.db?mode=ro", uri=True)
cents = answer(con, {level!r}, {region!r}, {start!r}, {end!r}, {mode!r})
with open("/app/answer.txt", "w") as f:
    f.write("%.2f\\n" % (cents / 100))
PY
"""

_NS: dict = {}
exec(SOLVER, _NS)  # noqa: S102 - our own source; the model form of every solution


def _solution(mode, level, region, start, end):
    def model(files):
        con = sqlite3.connect(":memory:")
        con.deserialize(files["data/shop.db"])
        cents = _NS["answer"](con, level, region, start, end, mode)
        con.close()
        return {"/app/answer.txt": "%.2f\n" % (cents / 100)}

    return Solution(_SHELL.format(solver=SOLVER, level=level, region=region, start=start, end=end, mode=mode), model)


SCHEMA = {
    1: [
        "CREATE TABLE customers (id INTEGER PRIMARY KEY, name TEXT NOT NULL, region TEXT NOT NULL)",
        "CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(id), placed_at TEXT, amount_cents INTEGER NOT NULL, refunded_cents INTEGER, deleted_at TEXT)",
    ],
    2: [
        "CREATE TABLE customers (id INTEGER PRIMARY KEY, name TEXT NOT NULL, region TEXT NOT NULL, deleted_at TEXT)",
        "CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(id), created_at TEXT NOT NULL, placed_at TEXT, amount_cents INTEGER NOT NULL, refunded_cents INTEGER, deleted_at TEXT)",
    ],
    3: [
        "CREATE TABLE customers (id INTEGER PRIMARY KEY, name TEXT NOT NULL, deleted_at TEXT)",
        "CREATE TABLE addresses (id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(id), region TEXT NOT NULL, city TEXT NOT NULL, is_primary INTEGER NOT NULL)",
        "CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers(id), region TEXT NOT NULL, created_at TEXT NOT NULL, placed_at TEXT, amount_cents INTEGER NOT NULL, refunded_cents INTEGER, deleted_at TEXT)",
    ],
}
CITIES = {"north": ["Aberdeen", "Tromso"], "south": ["Seville", "Naples"], "east": ["Krakow", "Riga"], "west": ["Porto", "Galway"], "central": ["Prague", "Vienna"]}


def _db_bytes(level, customers, addresses, orders):
    """The database file sqlite3 writes for these rows, with a host-independent header."""
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "shop.db")
        con = sqlite3.connect(path)
        con.execute("PRAGMA page_size = 4096")
        con.execute("PRAGMA secure_delete = ON")  # zero freed space, which versions otherwise fill differently
        for stmt in SCHEMA[level]:
            con.execute(stmt)
        ccols = ["id", "name"] + (["region"] if level < 3 else []) + (["deleted_at"] if level >= 2 else [])
        con.executemany(f"INSERT INTO customers ({', '.join(ccols)}) VALUES ({', '.join('?' * len(ccols))})", [[c[k] for k in ccols] for c in customers])
        if level == 3:
            acols = ["id", "customer_id", "region", "city", "is_primary"]
            con.executemany(f"INSERT INTO addresses ({', '.join(acols)}) VALUES (?, ?, ?, ?, ?)", [[a[k] for k in acols] for a in addresses])
        ocols = ["id", "customer_id"] + (["region"] if level == 3 else []) + (["created_at"] if level >= 2 else []) + ["placed_at", "amount_cents", "refunded_cents", "deleted_at"]
        con.executemany(f"INSERT INTO orders ({', '.join(ocols)}) VALUES ({', '.join('?' * len(ocols))})", [[o[k] for k in ocols] for o in orders])
        con.commit()
        con.close()
        with open(path, "rb") as f:
            data = bytearray(f.read())
    data[96:100] = struct.pack(">I", SQLITE_VERSION_FIELD)
    return bytes(data)


def _ts(dt):
    return dt.strftime("%Y-%m-%d %H:%M:%S")


def build(ctx):
    rng, p = ctx.rng, ctx.params
    level = p["level"]
    month = rng.randint(3, 10)
    region = rng.choice(REGIONS)
    start, end = datetime(2026, month, 1), datetime(2026, month + 1, 1)
    others = [r for r in REGIONS if r != region]

    # Customers: (primary region, deleted?, extra address regions)
    custs = []
    for _ in range(p["n_customers"]):
        custs.append({"region": rng.choice(REGIONS) if rng.random() < 0.6 else region, "deleted": level >= 2 and rng.random() < 0.08, "extra": []})
    in_region = [i for i, c in enumerate(custs) if c["region"] == region and not c["deleted"]]
    if len(in_region) < 4:
        raise Reject("too few live customers in the region")
    if level >= 2:  # a deleted customer of the region
        k = rng.choice([i for i in range(len(custs)) if i not in in_region[:3]])
        custs[k].update(region=region, deleted=True)
    if level == 3:
        for c in custs:
            c["extra"] = [rng.choice(REGIONS) for _ in range(rng.choice([0, 0, 1, 2]))]
        custs[in_region[0]]["extra"] = [region]  # double-counted by a join over all addresses
        outsider = rng.choice([i for i, c in enumerate(custs) if c["region"] != region and not c["deleted"]])
        custs[outsider]["extra"] = [region]  # counted by "any address in the region"
    live_region = [i for i, c in enumerate(custs) if c["region"] == region and not c["deleted"]]

    orders = []

    def order(cust, placed, *, created=None, refund="draw", deleted=False):
        amount = rng.randint(5, 400) * 100 + rng.choice([0, 0, 49, 99, 50, 25])
        if refund == "draw":
            refund = rng.choices([None, 0, "part"], weights=[80, 8, 12])[0]
        if refund == "part":
            refund = rng.randint(1, amount // 100) * 50  # at most half the amount
        if created is None:
            created = (placed or start) - timedelta(minutes=rng.randint(3, 600))
        wh = custs[cust]["region"] if rng.random() < 0.6 else rng.choice(REGIONS)
        orders.append({"customer_id": cust, "placed": placed, "created": created, "amount_cents": amount, "refunded_cents": refund, "deleted": deleted, "region": wh})

    def in_month():
        return start + timedelta(days=rng.randint(1, (end - start).days - 2), seconds=rng.randint(0, 86399))

    # background: any customer, two months either side of the target month
    for _ in range(p["n_orders"]):
        placed = start + timedelta(days=rng.randint(-55, 85), seconds=rng.randint(0, 86399))
        order(rng.randrange(len(custs)), placed, deleted=rng.random() < 0.05)
    # planted, in the target month for live customers of the region
    for _ in range(3):
        order(rng.choice(live_region), in_month(), refund="part")  # refunds: `gross` overcounts
    for _ in range(4):
        order(rng.choice(live_region), in_month(), refund=None)  # NULL refunds: `null-drop` undercounts
    order(rng.choice(live_region), in_month(), deleted=True)  # `deleted-orders` overcounts
    if level >= 2:
        deleted_cust = [i for i, c in enumerate(custs) if c["region"] == region and c["deleted"]]
        order(rng.choice(deleted_cust), in_month())  # `deleted-customers` overcounts
        for _ in range(2):  # opened the evening before the month starts: `created-at` misses them
            placed = start + timedelta(minutes=rng.randint(5, 300))
            order(rng.choice(live_region), placed, created=start - timedelta(minutes=rng.randint(10, 600)))
        for _ in range(rng.randint(2, 4)):  # abandoned carts opened in the month: `created-at` counts them
            order(rng.choice(live_region), None, created=in_month(), refund=None)
    if level == 3:
        order(in_region[0], in_month())
        order(outsider, in_month())
        for _ in range(2):  # shipped from the region's warehouse for a customer elsewhere, and the reverse
            o_cust = rng.choice([i for i, c in enumerate(custs) if c["region"] != region and not c["deleted"] and i != outsider])
            order(o_cust, in_month())
            orders[-1]["region"] = region
            order(rng.choice(live_region), in_month())
            orders[-1]["region"] = rng.choice(others)

    # Assign ids in placement order, like an auto-increment column.
    rng.shuffle(orders)
    orders.sort(key=lambda o: o["created"])
    names = [f"{rng.choice(FIRST_NAMES)} {rng.choice(LAST_NAMES)}" for _ in custs]
    cid = [i + 1 for i in range(len(custs))]
    customers = []
    for i, c in enumerate(custs):
        deleted_at = _ts(datetime(2026, 1, 1) + timedelta(days=rng.randint(0, 270), seconds=rng.randint(0, 86399))) if c["deleted"] else None
        customers.append({"id": cid[i], "name": names[i], "region": c["region"], "deleted_at": deleted_at})
    addresses = []
    if level == 3:
        for i, c in enumerate(custs):
            regs = [(c["region"], 1)] + [(r, 0) for r in c["extra"]]
            rng.shuffle(regs)
            for r, prim in regs:
                addresses.append({"id": len(addresses) + 1, "customer_id": cid[i], "region": r, "city": rng.choice(CITIES[r]), "is_primary": prim})
    rows = []
    for n, o in enumerate(orders):
        deleted_at = _ts((o["placed"] or o["created"]) + timedelta(days=rng.randint(1, 20))) if o["deleted"] else None
        rows.append({
            "id": 1000 + n,
            "customer_id": cid[o["customer_id"]],
            "region": o["region"],
            "created_at": _ts(o["created"]),
            "placed_at": _ts(o["placed"]) if o["placed"] else None,
            "amount_cents": o["amount_cents"],
            "refunded_cents": o["refunded_cents"],
            "deleted_at": deleted_at,
        })
    db = _db_bytes(level, customers, addresses, rows)

    s, e = _ts(start), _ts(end)
    con = sqlite3.connect(":memory:")
    con.deserialize(db)
    cents = _NS["answer"](con, level, region, s, e, "oracle")
    con.close()
    modes = ["null-drop", "gross", "deleted-orders"]
    if level >= 2:
        modes += ["deleted-customers", "created-at"]
    if level == 3:
        modes += ["address-join", "any-address", "order-region"]
    rules = "\n".join(f"- {r}" for r in RULES[level])
    return TaskSpec(
        instruction=INSTRUCTION.format(month=MONTHS[month - 3], region=region, rules=rules),
        files={"data/shop.db": db},
        grader=NumericAnswer("/app/answer.txt", cents / 100, abs_tol=0.005),
        oracle=_solution("oracle", level, region, s, e),
        shortcuts={m: _solution(m, level, region, s, e) for m in modes},
        params={"level": level, "month": month, "region": region, "n_customers": p["n_customers"], "n_orders": p["n_orders"]},
    )


